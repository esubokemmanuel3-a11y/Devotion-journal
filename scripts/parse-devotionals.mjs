#!/usr/bin/env node
// Converts raw CCEL "Morning and Evening" text into src/data/devotionals.js
//
// Usage:
//   node scripts/parse-devotionals.mjs <input-dir> [output-file]
//
// How to get the input files:
//   For each month, open the CCEL page (e.g. ccel.org/s/spurgeon/morn_eve/ME01AM.html),
//   Ctrl+A, Ctrl+C, and paste into a .txt file inside <input-dir>. Filenames don't
//   matter — the month/day/AM-PM come from the "* MM/DD/AM" markers already in the text.
//   24 files total (12 months x AM/PM) covers the whole year.

import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

const inputDir = process.argv[2];
const outputFile = process.argv[3] || 'src/data/devotionals.js';

if (!inputDir) {
  console.error('Usage: node scripts/parse-devotionals.mjs <input-dir> [output-file]');
  process.exit(1);
}

const entryRe = /\*\s*(\d{2})\/(\d{2})\/(AM|PM)\s*\n/g;

function parseFile(text) {
  const results = [];
  const matches = [...text.matchAll(entryRe)];
  for (let i = 0; i < matches.length; i++) {
    const [full, mm, dd, slot] = matches[i];
    const start = matches[i].index + full.length;
    const end = i + 1 < matches.length ? matches[i + 1].index : text.length;
    const block = text.slice(start, end).trim();
    results.push({ month: parseInt(mm, 10), day: parseInt(dd, 10), slot: slot.toLowerCase(), block });
  }
  return results;
}

function parseBlock(block) {
  const lines = block.split('\n');
  let refIndex = -1;
  for (let i = 0; i < lines.length; i++) {
    if (/^\s*--\s*\S/.test(lines[i])) { refIndex = i; break; }
  }
  if (refIndex === -1) return null;

  const verseLines = lines.slice(0, refIndex);
  const reference = lines[refIndex].trim().replace(/^--\s*/, '');
  const bodyLines = lines.slice(refIndex + 1);

  const verse = verseLines
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^"+|"+$/g, '');

  const bodyText = bodyLines.join('\n');
  const paragraphs = bodyText
    .split(/\n\s*\n/)
    .map((p) => p.split('\n').map((l) => l.trim()).filter(Boolean).join(' ').trim())
    .filter(Boolean);
  const body = paragraphs.join('\n\n');

  return { verse, reference, body };
}

const files = readdirSync(inputDir).filter((f) => f.endsWith('.txt'));
if (files.length === 0) {
  console.error(`No .txt files found in ${inputDir}`);
  process.exit(1);
}

const devotionals = {};
let count = 0;

for (const file of files) {
  const text = readFileSync(join(inputDir, file), 'utf-8');
  const parsedEntries = parseFile(text);
  for (const { month, day, slot, block } of parsedEntries) {
    const parsed = parseBlock(block);
    if (!parsed) {
      console.warn(`  Skipped ${file} ${month}/${day}/${slot} — couldn't find reference line`);
      continue;
    }
    const key = `${month}-${day}`;
    devotionals[key] = devotionals[key] || {};
    devotionals[key][slot === 'am' ? 'morning' : 'evening'] = parsed;
    count++;
  }
}

function jsStringLiteral(str) {
  return JSON.stringify(str);
}

function jsTemplateLiteral(str) {
  return '`' + str.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
}

const sortedKeys = Object.keys(devotionals).sort((a, b) => {
  const [am, ad] = a.split('-').map(Number);
  const [bm, bd] = b.split('-').map(Number);
  return am - bm || ad - bd;
});

let out = `// Charles Spurgeon, "Morning and Evening" — public domain (source: CCEL).\n`;
out += `// Auto-generated by scripts/parse-devotionals.mjs — do not hand-edit; re-run instead.\n`;
out += `// Keyed "M-D" (e.g. "1-1" = Jan 1). Each date has morning/evening: { verse, reference, body }.\n\n`;
out += `export const devotionals = {\n`;

for (const key of sortedKeys) {
  const entry = devotionals[key];
  out += `  '${key}': {\n`;
  for (const slot of ['morning', 'evening']) {
    if (!entry[slot]) continue;
    const { verse, reference, body } = entry[slot];
    out += `    ${slot}: {\n`;
    out += `      verse: ${jsStringLiteral(verse)},\n`;
    out += `      reference: ${jsStringLiteral(reference)},\n`;
    out += `      body: ${jsTemplateLiteral(body)},\n`;
    out += `    },\n`;
  }
  out += `  },\n`;
}

out += `};\n\n`;
out += `export function getDevotionalFor(month, day) {\n`;
out += `  return devotionals[\`${'${month}-${day}'}\`] ?? null;\n`;
out += `}\n`;

writeFileSync(outputFile, out, 'utf-8');
console.log(`Wrote ${sortedKeys.length} days (${count} entries) to ${outputFile}`);